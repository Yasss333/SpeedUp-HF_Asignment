async def seed_demo(store, user_id, expires_at):
    now = datetime.now(UTC)
    for (name, email), examples in DEMO_INBOXES.items():
        client_id = str(uuid4())
        await store.insert(
            "clients",
            {
                "_id": client_id,
                "tenant_id": user_id,
                "name": name,
                "email": email,
                "rules": DEFAULT_RULES,
                "expires_at": expires_at,
            },
        )
        for subject, body, owner, priority, category, is_read in examples:
            await store.insert(
                "emails",
                {
                    "_id": str(uuid4()),
                    "tenant_id": user_id,
                    "client_id": client_id,
                    "sender": f"{category.lower()}@example.com",
                    "subject": subject,
                    "body": body,
                    "owner": owner,
                    "priority": priority,
                    "category": category,
                    "summary": body,
                    "reasoning": f"Demo routing: {category} belongs to {owner}.",
                    "suggested_draft": ""
                    if owner == "FYI"
                    else "Thank you for your email. I will review this and follow up shortly.",
                    "is_read": is_read,
                    "has_reply": False,
                    "read_no_reply": is_read,
                    "status": "PENDING",
                    "triage_source": "DEMO",
                    "created_at": now,
                    "updated_at": now,
                    "approved_at": None,
                    "sent_at": None,
                    "version": 1,
                    "expires_at": expires_at,
                    "priority_rank": {"HIGH": 0, "MEDIUM": 1, "LOW": 2}[priority],
                },
            )
